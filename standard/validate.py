                # `draft`, а тип, НЕ объявленный знанием. То есть сообщение запрещало
                # ровно то единственное, что помогает, и человек, сделавший по нему всё
                # правильно, оставался с прежней ошибкой и без объяснения. Разница между
                # служебным типом и необъявленным доменным здесь и есть разница между
                # гашением и починкой, поэтому оба названы поимённо.
