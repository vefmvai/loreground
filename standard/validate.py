    # Отличить тёзок от настоящего дубля можно только по `title` КАЖДОГО файла.
    title_by_file = {}     # путь -> `title`
    temporal_notes = []
    revisit_notes = []     # заметки со сроком перепроверки (§ 3.4)
    fm_problems = list(encoding_problems)
    for f in base_files:
        text = texts[f]
        base = os.path.basename(f)[:-3]
