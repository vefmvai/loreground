COMPUTED_KEY_RE = re.compile(r"^(count|total|progress|percent)$|_(count|total)$")


def dir_not_empty(path: str) -> bool:
    """В папке есть хоть одна запись.

    Нужно, чтобы отличить «папка пуста» от «в папке лежит не то»: человеку это
    разные починки. Отказ доступа считаем пустотой намеренно — сообщение о нём
    увело бы от настоящей беды (заметок нет ни в том, ни в другом случае).
    """
    try:
        return bool(os.listdir(path))
    except OSError:
        return False


# Последний файл, который валидатор трогал. Нужен ровно для одного: если прогон
# всё-таки упадёт, человек обязан узнать, НА ЧЁМ он упал. Трассировка называет
# строки валидатора и библиотеки, но не заметку — и виноватую искали делением базы
# пополам. Это не «мы поймали все падения», а «непойманное больше не безадресно».
ПОСЛЕДНИЙ_ФАЙЛ = None


def is_excluded(path: str, root: str = None) -> bool:
    """Файл лежит в служебной подпапке ВНУТРИ базы (`_templates/`, `_personal/`).

    Считается путь ОТНОСИТЕЛЬНО базы, а не весь. Пока смотрели весь путь, база,
    лежащая под предком с таким именем, отсеивалась целиком — а правило «личное
    прячем» велит держать приватные базы ровно так. Прогон отвечал «все .md
    в служебных подпапках, заметки лежат РЯДОМ», и совет было не выполнить:
    виновато имя папки-предка, а не расположение заметок.
    """
    if root:
        try:
            path = os.path.relpath(path, root)
        except ValueError:
            pass          # разные диски (Windows) — судим по полному пути, как раньше
    p = "/" + path.replace(os.sep, "/").lstrip("/")
    return "/_templates/" in p or "/_personal/" in p


def read(path: str):
    """(текст, проблема|None). Файл не в UTF-8 — это дефект базы, а не повод упасть.

    Падение трейсбеком на одном файле читается как «сломался инструмент»,
    а не «в базе один битый файл».
    """
    global ПОСЛЕДНИЙ_ФАЙЛ
    ПОСЛЕДНИЙ_ФАЙЛ = path
    # Открывать разрешено только ОБЫЧНЫЙ файл. FIFO и символьное устройство
    # (`/dev/zero`) не ошибаются при открытии — они блокируются навсегда, и
    # прогон висит без вывода и без кода выхода. Отказ ошибкой шумит, зависание
    # молчит; второе хуже. Каталоги и битые симлинки отсекаются здесь же.
    if not os.path.isfile(path):
        return "", f"{path}: не обычный файл (FIFO, устройство, каталог или битая ссылка) — не прочитан"
    try:
        # utf-8-sig, а не utf-8: BOM в начале файла ставят редакторы Windows, и он
        # НЕ пробельный символ — `"﻿---".strip()` не равно `"---"`. Пока читали
        # обычным utf-8, такой файл получал вердикт «не начинается со строки ---»:
        # в папочной раскладке это была честная ошибка frontmatter, а в раскладке по
        # метке — молчаливое выпадение из базы. Тот самый вход в тишину, ради закрытия
        # которого и заводились проверки 25 и 26, только не через значение `type`,
        # а через чтение файла. На файлах без BOM utf-8-sig ведёт себя как utf-8.
        with open(path, encoding="utf-8-sig") as fh:
            return fh.read(), None
    except UnicodeDecodeError:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read(), (f"{path}: файл не в UTF-8 — часть символов заменена "
                               f"при чтении; перекодируй, иначе поля читаются неверно")
    except OSError as e:
        # Отказ в доступе, битый симлинк, каталог с именем *.md — то же самое:
        # файл не прочитан, значит НЕ проверен. Молча пропустить нельзя (§ 8.1:
        # «отказ в доступе — это „не проверено“, а не „чисто“»), уронить
        # трейсбеком тоже: один файл не должен отменять прогон.
        return "", f"{path}: файл не прочитан ({type(e).__name__}) — считается непроверенным"


def parse_aliases(text: str):
    """Запасной разбор синонимов: только инлайновая форма `aliases: [A, B]`."""
    m = ALIASES_RE.search(text)
    if not m:
        return []
    out = []
    for a in m.group(1).split(","):
        a = a.strip().strip('"').strip("'").strip()
        if a:
            out.append(a)
    return out


def note_aliases(data, text: str) -> list:
    """Синонимы заметки из разобранного frontmatter — в ЛЮБОЙ форме YAML-списка.

    Регэксп `ALIASES_RE` видит только инлайновую форму `aliases: [A, B]`. Блочная
    форма (дефисами) для него не существует, и все её синонимы пропадали из
    множества известных имён: ссылка на законный alias объявлялась битой, а
    заметка, на которую ссылались только по синониму, — сиротой. Ложная ошибка
    на честной базе. Регэксп остаётся запасным путём: при битом YAML
    разобранных полей нет вовсе.
    """
    if isinstance(data, dict) and data.get("aliases") is not None:
        value = data.get("aliases")
        if isinstance(value, str):
            value = [value]
        if isinstance(value, list):
            return [str(a).strip() for a in value if str(a).strip()]
    return parse_aliases(text)


def frontmatter_block(text: str):
    """Вернуть (блок, None) или (None, описание проблемы структуры).

    Границы ищутся по СТРОКЕ, которая целиком состоит из `---`. Резать по первому
    попавшемуся `---` нельзя: длинное тире внутри значения — `ref: "Иванов ---
    Петров"` — обрезало бы frontmatter посередине, и поля ниже разреза
    перестали бы существовать. Ложь про здоровый файл дороже пропущенной
    ошибки: по ней идут чинить то, что не сломано (§ 10.2).
    """
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        # Сообщение называет следующий шаг, а не только нарушенное правило. Строка,
        # описывающая одну болезнь, читается как приговор: чинящий знает, что не так,
        # и не знает, чем закрыть, — а угаданный наспех frontmatter даёт не тот `type`
        # и половину полей. Адрес шаблона называется по имени файла: где лежит комплект,
        # знает тот, кто его ставил, а в режиме «копия» шаблоны и вовсе остаются
        # у поставщика (§ 9.3) — путь тут был бы выдуман.
        return None, ("нет frontmatter (файл не начинается со строки ---). "
                      "Взять за образец: templates/knowledge.md в комплекте стандарта; "
                      "обязательные поля — core.md § 3.1")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return "\n".join(lines[1:i]), None
    return None, "нет закрывающего --- у frontmatter"


def parse_frontmatter(path: str, text: str):
    """Вернуть (dict|None, [проблемы]). dict есть только при валидном YAML.

    Ветки «без PyYAML» здесь нет намеренно: прогон без библиотеки не начинается
    вовсе (гейт в main()). Мягкая деградация означала бы exit 0 на базе
    с ошибками: битый YAML некому заметить.
    """
    global ПОСЛЕДНИЙ_ФАЙЛ
    ПОСЛЕДНИЙ_ФАЙЛ = path
    problems = []
    block, structural = frontmatter_block(text)
    if structural:
        return None, [f"{path}: {structural}"]
    try:
        data = yaml.load(block, Loader=StrictNoDuplicateLoader)
    except DuplicateKeyError as e:
        return None, [f"{path}: {e}"]
    except RecursionError:
        return None, [f"{path}: frontmatter вложен слишком глубоко — не разобран"]
    except (ValueError, TypeError) as e:
        # Разборщик YAML сам собирает даты и на несуществующей (`created: 2024-02-30`)
        # бросает ValueError, а не YAMLError. Ловить это надо здесь, а не наверху:
        # снаружи известен только факт падения, и человек получал трассировку без
        # имени файла — искать виноватую заметку приходилось делением базы пополам.
        # Хуже другое: пока в той же заметке был битый `title`, разбор падал раньше
        # и до даты не доходил, то есть КРАХ ПОЯВЛЯЛСЯ КАК СЛЕДСТВИЕ ПОЧИНКИ по § 10.2.
        # Это дефект одной заметки, а не поломка прогона: код 1, а не 2.
        return None, [f"{path}: {дата_или_нет(e)}"]
    except yaml.YAMLError as e:
        # Сдвиг на 1: координаты приходят от разборщика в номерах БЛОКА, а блок
        # начинается со второй строки файла — первая занята `---`. Без сдвига
        # сообщение звало на строку выше настоящей, и чинящий смотрел не туда.
        return None, [f"{path}{yaml_error_place(e, 1)}: YAML-ошибка — "
                      + yaml_error_text(e, block)]
    if not isinstance(data, dict):
        return None, [f"{path}: frontmatter не разобрался в набор полей (ключ: значение)"]
    for key in REQUIRED_FRONTMATTER_KEYS:
        if key not in data:
            problems.append(f"{path}: нет обязательного ключа `{key}`")
    return data, problems


# Что именно сказала библиотека — по-русски. § 10.2 велит чинить битый YAML ПЕРВЫМ:
# пока заметка не разбирается, для девяти проверок её как будто нет. Значит первое
# сообщение отчёта обязано быть самым понятным, а оно было самым слабым — английским
# и обрезанным по первой строке исключения. Обрезалось при этом ровно то место, где
# библиотека говорит, ЧЕГО ждала: `str(err)` начинается с контекста («while scanning
# a simple key»), а суть стоит второй строкой.
YAML_ПОЯСНЕНИЯ = (
    ("could not find expected ':'",      "после имени поля нет двоеточия"),
    ("mapping values are not allowed",    "двоеточие там, где YAML ждал продолжение предыдущего "
                                          "поля. Либо у строки ВЫШЕ нет своего двоеточия, либо "
                                          "двоеточие попало внутрь значения — тогда возьми "
                                          "значение в кавычки: `ref: \"Иванов: сборник\"`"),
    ("expected <block end>",              "разъехались отступы: строка не встала ни в список, ни в блок"),
    ("that cannot start any token",       "таб вместо пробелов — отступы в YAML только пробелами"),
    ("found unexpected end of stream",    "блок оборвался на полуслове"),
    ("expected the node content",         "у поля нет значения"),
    ("found unexpected ':'",              "двоеточие там, где ждали текст"),
    ("while parsing a block mapping",     "не дочитан набор полей"),
    ("found character",                   "символ, с которого поле начинаться не может"),
)


def yaml_error_text(err, block) -> str:
    """Человеческое объяснение ошибки YAML + сама виноватая строка.

    Берутся ОБЕ половины исключения: `context` («где читали») и `problem` («чего
    ждали»). Прежде печаталась только первая строка `str(err)` — то есть контекст,
    а суть терялась. Плюс показывается сама строка файла: искать её глазами по
    номеру — работа, которую машина уже сделала.
    """
    problem = str(getattr(err, "problem", "") or "")
    context = str(getattr(err, "context", "") or "")
    оригинал = "; ".join(x for x in (context, problem) if x) or str(err).splitlines()[0]
    объяснение = next((рус for англ, рус in YAML_ПОЯСНЕНИЯ
                       if англ in problem or англ in context), "")
    куски = [объяснение] if объяснение else []
    mark = getattr(err, "problem_mark", None)
    if mark is not None and block is not None:
        строки = block.split("\n")
        if 0 <= mark.line < len(строки):
            куски.append(f"строка: `{строки[mark.line].rstrip()}`")
    куски.append(f"дословно от разборщика: {оригинал}")
    return ". ".join(куски)


def дата_или_нет(err) -> str:
    """Человеческое объяснение падения конструктора YAML."""
    текст = str(err)
    m = re.search(r"day (\d+) must be in range 1\.\.(\d+) for month (\d+) in year (\d+)", текст)
    if m:
        return (f"даты не существует: в {m.group(3)}-м месяце {m.group(4)} года "
                f"{m.group(2)} дней, а в поле стоит {m.group(1)}-е. Даты стандарта — "
                f"YYYY-MM-DD (§ 3.5); выдуманная дата хуже отсутствующей")
    return (f"frontmatter не разобрался ({type(err).__name__}): {текст}. "
            f"Чаще всего это значение, которое YAML пытается прочесть как дату или число")


def yaml_error_place(err, сдвиг: int = 0) -> str:
    """«:строка:столбец» из исключения PyYAML, если координаты есть.

    Сообщение без координат заставляет искать ошибку глазами по всему блоку —
    на чужой базе это первое, обо что спотыкается починка (§ 10.2). `сдвиг` —
    сколько строк файла стоит перед разобранным куском.
    """
    mark = getattr(err, "problem_mark", None)
    if mark is None:
        return ""
    return f":{mark.line + 1 + сдвиг}:{mark.column + 1}"


def link_names(value) -> list:
    """Из YAML-значения (список строк '[[Имя]]' / строк) — чистые имена."""
    names = []
    if not isinstance(value, list):
        return names
    for item in value:
        if not isinstance(item, str):
            continue
        m = LINK_RE.search(item)
        if m:
            names.append(m.group(1).strip())
            continue
        # Markdown-форма `[текст](файл.md)` — та же ссылка, записанная иначе. Пока
        # её здесь не было, `sources: ["[[И]]", "[И](И.md)"]` считались ДВУМЯ разными
        # корнями: проверка 5 печатала «✅ Консенсус обеспечен корнями» на одном файле,
        # названном дважды. Базу при этом краснила проверка 17 («не ведёт ни в одну
        # заметку»), то есть зелёного прогона обход не давал — но в отчёте стояла
        # неправда, а отчёт и есть то, что человек читает. Ту же слепоту к markdown-
        # форме граф пережил отдельно: дом у разбора ссылок должен быть один.
        md = MD_LINK_RE.search(item)
        if md:
            names.append(os.path.basename(md.group(1))[:-3].strip())
            continue
        names.append(item.strip())
    return [n for n in names if n]


def root_ids(data) -> set:
    """root_id заметки-источника (§ 4.4) — всегда множество, даже если записан строкой."""
    if not isinstance(data, dict):
        return set()
    value = data.get("root_id")
    if value is None:
        return set()
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list):
        return set()
    # Идентификатор нормализуется ТОЙ ЖЕ функцией, что и имена, — иначе нормализация
    # сделана наполовину, а половинчатая опаснее отсутствующей: она создаёт впечатление,
    # что класс закрыт. Одного регистра мало: `reg-2024-017` против
    # `reg-2024-<U+200B>017` (невидимый пробел, на экране неотличимо) снова давали два
    # корня — тот же обход, ради которого правка и делалась. `norm_name` берёт NFC,
    # чистку невидимых символов и регистр разом.
    return {norm_name(v) for v in value if str(v).strip()}


def independent_roots(data: dict, source_roots=None, name_to_base=None, with_groups=False,
                      supersede_pairs=None):
    """Число независимых корней: sources, схлопнутые по same_root и общему root_id (§ 5.3 п. 5).

    source_roots: имя источника (lowercase) -> set(root_id). Источники, делящие
    хотя бы один root_id, — один корень в ЛЮБОЙ заметке (§ 4.4).
    """
    raw_sources = link_names(data.get("sources"))
    if not raw_sources:
        # Форму возврата задаёт флаг, и ранний выход обязан её соблюдать наравне с
        # обычным. Пока он отдавал голое число, вызывающий с `with_groups=True` падал
        # на распаковке — то есть валидатор ронял ПРОГОН ровно на самой частой ошибке
        # новичка: `consensus: confirmed` при пустом списке источников. Вместо «вердикт
        # не обеспечен корнями» человек получал «прогон не состоялся» и шёл чинить
        # установку вместо заметки.
        return (0, []) if with_groups else 0

    # Один и тот же источник, названный двумя своими законными именами (title и
    # alias, имя файла и заголовок), — ОДИН корень. Счёт сырых строк разрешал бы
    # прачечную из одного файла.
    #
    # Приведение к каноническому имени делается ОДИН раз и применяется ко ВСЕМУ
    # дальнейшему счёту — и к `sources`, и к группам `same_root`. Пока канон был
    # только у `sources`, оставалась дыра ровно в той половине, где зависимость
    # объявлена честно: источник процитирован алиасом, группа названа заголовком,
    # строки не совпали, группа не связалась — и `confirmed` проходил на одном
    # корне. Обход бил в проверку 5, единственную машину слоя доверия, и обходился
    # он не подлогом, а законным вторым именем.
    def canon(name):
        key = norm_name(name)
        return name_to_base.get(key, key) if name_to_base else key

    sources, seen_canon = [], set()
    for src in raw_sources:
        key = canon(src)
        if key not in seen_canon:
            seen_canon.add(key); sources.append(key)

    groups = []
    for grp in data.get("same_root") or []:
        names = {canon(n) for n in link_names(grp)} if isinstance(grp, list) else set()
        if names:
            groups.append(names)
    # Пара, связанная `supersedes`, — один корень, и это свойство пары, а не
    # утверждения: «новая редакция отменяет старую» значит «это один документ».
    if supersede_pairs:
        for пара in supersede_pairs:
            канон = {canon(n) for n in пара}
            общее = канон & set(sources)
            if len(общее) > 1:
                groups.append(общее)
    # группы по общему root_id: свойство пары источников, не утверждения (§ 4.4)
    if source_roots:
        canon_roots = {}
        for name, rids in source_roots.items():
            canon_roots.setdefault(canon(name), set()).update(rids)
        by_root = {}
        for s in sources:
            for rid in canon_roots.get(s, ()):
                by_root.setdefault(rid, set()).add(s)
        groups.extend(g for g in by_root.values() if len(g) > 1)
    # объединить пересекающиеся группы (общий член = общий корень)
    merged = []
    for g in groups:
        g = set(g)
        rest = []
        for m in merged:
            if m & g:
                g |= m
            else:
                rest.append(m)
        merged = rest + [g]
    # Разбиение источников на корни собирается ЦЕЛИКОМ, а не считается на лету:
    # прежде функция возвращала одно число, и сообщение проверки 5 говорило «sources
    # схлопнуты», не называя — какие именно и во что. Чинящий заметку был вынужден
    # пересобирать разбиение в голове по same_root и root_id, то есть повторять
    # работу, которую машина только что сделала и выбросила.
    partition, seen = [], set()
    for s in sources:
        if s in seen:
            continue
        grp = next((m for m in merged if s in m), None)
        члены = [x for x in sources if x in grp] if grp else [s]
        seen |= set(члены)
        partition.append(члены)
    return (len(partition), partition) if with_groups else len(partition)


def parse_month(value):
    """(год, месяц) из даты стандарта или None, если дата не разобралась.

    None здесь означает «не знаю», и вызывающий обязан считать это дефектом, а
    не свежестью. Разбор fail-open означал бы, что `2024-5` и `май 2024`
    молча выпадают из отчёта о протухании и выглядят свежими, — а § 3.4
    объявляет подделку свежести роднёй выдуманного источника.
    """
    m = DATE_RE.match(str(value or "").strip().strip('"').strip("'"))
    if not m:
        return None
    return int(m.group(1)), int(m.group(2))


def months_between(a, b) -> int:
    """Сколько месяцев от (год, месяц) a до (год, месяц) b."""
    return (b[0] - a[0]) * 12 + (b[1] - a[1])


# Кириллические буквы, которые на экране не отличить от латинских. Список закрытый
# и короткий: он нужен, чтобы отличить ПОДМЕНУ буквы от слова, просто написанного
# по-русски. Пока подсказка перечисляла подряд все не-ASCII буквы, на `подтверждено`
# она выдавала «ж U+0436» — а «ж» ни на что латинское не похожа, и человек читал
# подсказку про омоглифы там, где омоглифа нет. Ложная подсказка хуже отсутствия:
# она уводит чинить не то.
CYR_LOOKALIKE = {
    "а": "a", "в": "b", "е": "e", "к": "k", "м": "m", "н": "h", "о": "o", "р": "p",
    "с": "c", "т": "t", "у": "y", "х": "x", "і": "i", "ј": "j", "ѕ": "s", "һ": "h",
    "А": "A", "В": "B", "Е": "E", "З": "3", "К": "K", "М": "M", "Н": "H", "О": "O",
    "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X", "Ј": "J", "Ѕ": "S", "І": "I",
}
# Латинские буквы, которые на экране не отличить от кириллических, — обратная сторона.
LAT_LOOKALIKE = {v: k for k, v in CYR_LOOKALIKE.items() if v.isalpha()}

WORD_RE = re.compile(r"[^\W\d_]+", re.UNICODE)


def is_cyr(ch: str) -> bool:
    return "Ѐ" <= ch <= "ӿ"


def is_lat(ch: str) -> bool:
    return ("a" <= ch <= "z") or ("A" <= ch <= "Z")


def участки(w):
    """Слово, разложенное на непрерывные куски одной азбуки: [('lat','SEO'), ('cyr','шник')]."""
    куски = []
    for ch in w:
        вид = "lat" if is_lat(ch) else ("cyr" if is_cyr(ch) else "прочее")
        if куски and куски[-1][0] == вид:
            куски[-1][1] += ch
        else:
            куски.append([вид, ch])
    return [(в, т) for в, т in куски if в != "прочее"]


def mixed_script_words(s):
    """Слова, где азбуки намешаны ВНУТРИ слова ПОДМЕНОЙ, а не словообразованием.

    Первая граница — слово, а не строка: `Витамин D` — два слова, и латинская `D`
    там законна. Её мало: `Работа в Excelе`, `PDFка`, `SEOшник` — это тоже одно слово
    с двумя азбуками, и это обычное русское словообразование от латинской основы.
    Проверка, краснеющая на них, — ошибка, а ошибку выключают.

    Вторая граница — РАСКЛАД участков, а не счёт букв. Русское окончание приклеивается
    к латинской основе ОДНИМ куском в конце, и основа при этом настоящая — от двух букв:

        SEO|шник   Excel|е   PDF|ка   Nginx|а      — два участка, латинский первый и длинный
        K|офеин    С|laude                          — латинский участок в одну букву: подмена
        Вит|a|мин  P|о|stgres                       — три участка: подмена в середине

    Односложное правило: подмена — это либо три и более участков, либо два, где ПЕРВЫЙ
    короче двух букв. Всё остальное — словообразование, и оно молчит.
    """
    out = []
    for w in WORD_RE.findall(str(s or "")):
        куски = участки(w)
        виды = {в for в, _ in куски}
        if len(виды) < 2:
            continue
        if len(куски) == 2 and куски[0][0] == "lat" and len(куски[0][1]) >= 2:
            continue   # латинская основа + русское окончание: `SEOшник`, `Excelе`
        кир = [ch for ch in w if is_cyr(ch)]
        лат = [ch for ch in w if is_lat(ch)]
        # Чужие — те, которых меньше: подменяют одну-две буквы, а не половину слова.
        чужие = лат if len(лат) <= len(кир) else кир
        азбука = "латиница" if чужие is лат else "кириллица"
        буквы = ", ".join(f"«{ch}» U+{ord(ch):04X}" for ch in dict.fromkeys(чужие))
        out.append((w, азбука, буквы))
    return out


