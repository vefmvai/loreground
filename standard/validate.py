# «омоглиф» имеет смысл говорить только там, где подменой получено ПОХОЖЕЕ НА НАСТОЯЩЕЕ.
CORE_KEYS = (
    "title", "type", "schema_version", "status", "created", "tags", "aliases",
    "sources", "consensus", "temporal", "as_of", "revisit_after",
    "reliability", "source_type", "ref", "root_id", "same_root",
)


def латинизировать(s: str) -> str:
    """Отменить подмену: кириллические двойники заменить их латинскими оригиналами."""
    return "".join(CYR_LOOKALIKE.get(ch, ch) for ch in str(s))


def homoglyph_hint(value, годится=None) -> str:
    """Подсказка про подменённые буквы. «Омоглиф» — только там, где он есть.

    `reliability: 'А'` кириллической буквой выглядит на экране как правильное
    значение, и сообщение «не из словаря ядра ('a','b','c','f')» читается как
    баг валидатора, а не как ошибка в базе. Называем букву по коду — тогда видно,
    что она не та.

    Но «все буквы имеют латинских двойников» признаком подмены НЕ является: у слова
    `автор` двойники есть у всех пяти букв, и подсказка кричала «омоглиф» на честном
    русском слове, тогда как соседнее `год` получало спокойное «написано не латиницей».
    Один класс объяснялся двумя способами, и тревожный доставался более невинному.

    Признак теперь по существу: **отмени подмену и посмотри, получилось ли настоящее
    значение.** `sіngle` → `single` — есть в словаре, это подмена. `автор` → `abtop` —
    такого поля нет, значит слово просто написано по-русски. Что считать настоящим,
    решает вызывающий: у значений это словарь оси, у ключей — имена полей ядра.
    """
    s = str(value or "")
    чужие = [ch for ch in s if ord(ch) > 127]
    if not чужие:
        return ""
    подменённые = [ch for ch in dict.fromkeys(чужие) if ch in CYR_LOOKALIKE]
    похоже = (len(подменённые) == len(set(чужие))
              and годится is not None and годится(латинизировать(s)))
    if похоже:
        names = ", ".join(f"«{ch}» U+{ord(ch):04X} вместо латинской «{CYR_LOOKALIKE[ch]}»"
                          for ch in подменённые)
        return (f" ← омоглиф: {names}. На экране не отличить, для механики "
                f"это другое слово")
    return " ← слово написано не латиницей: словарь ядра английский (§ 3.5)"


def is_archived(text: str) -> bool:
    if ARCHIVE_STATUS_RE.search(text):
        return True
    # Шапка ищется в ТЕЛЕ, а не в первых строках файла: frontmatter — структурные
    # данные, и объявление архивности там уже есть, это `status: archived`. Слово
    # «архив» во frontmatter почти всегда говорит о ЧУЖОЙ заметке, а не об этой —
    # например пометка архивности на строке `sources:`, которую требует § 7.4.
    # Пока шапку искали по всему началу файла, такая пометка объявляла архивной
    # саму ссылающуюся заметку, и валидатор начинал требовать пометку уже на неё.
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        for n, line in enumerate(lines[1:], 1):
            if line.strip() == "---":
                lines = lines[n + 1:]
                break
    # ШАПКА — ЭТО ПЕРВАЯ СТРОКА ТЕЛА, и только она. Не «где-то в первых пятнадцати»:
    # § 7.4 требует помечать словом «архив» КАЖДУЮ ссылку на архив, поэтому такие
    # слова законно встречаются по всей заметке — в том числе у той, которая сама
    # архивом не является. Пока самообъявление искали в куске текста, любая заметка,
    # честно исполнившая § 7.4, объявляла архивом СЕБЯ, а архив исключён из проверки
    # ссылок целиком: правило наказывало собственное исполнение и заодно снимало
    # проверку. Чаще всего под это попадал индекс — у него ссылок больше всех.
    # Сужение до одной строки нужно потому, что отличить самообъявление от рассказа
    # о чужой заметке по словам нельзя: слова те же самые. Отличает МЕСТО — шапка
    # стоит первой и ни на что не ссылается. Ровно поэтому у структурного объявления
    # (`status: archived`) ограничений нет: оно однозначно по форме, а не по месту.
    первая = next((l for l in lines if l.strip()), "")
    # Различает не «есть ли на строке ссылка», а СТОИТ ЛИ МАРКЕР ДО НЕЁ.
    #   «**Исторический снимок.** Правила отменены; актуальное — [[Новый]].» — шапка:
    #      заметка объявляет архивом СЕБЯ и по § 6 п. 4 кладёт указатель на преемника;
    #   «- [[Приказ]] — исторический снимок» — пометка ЧУЖОЙ ссылки, шапкой не является.
    # Отбрасывать любую строку со ссылкой нельзя: идиоматичная шапка с указателем
    # перестала бы быть шапкой. Цена такой ошибки — не «одна ссылка не проверена»:
    # заметка перестаёт считаться архивом вовсе, а вместе с этим проверка 6
    # выключается для неё целиком.
    m = ARCHIVE_HEAD_HINT_RE.search(первая)
    if not m:
        return False
    ссылка = re.search(r"\[\[[^\]]+\]\]|\]\([^)]+\)", первая)
    return ссылка is None or m.start() < ссылка.start()


MAX_STATUS_PATH_UP = 6  # сколько уровней вверх искать путь статуса


def resolve_status_path(token: str, file_dir: str) -> bool:
    """Найти файл по точному пути или префиксу — от каталога файла и его предков.

    Рабочего каталога здесь нет намеренно. Иначе один и тот же файл проверялся бы
    по-разному в зависимости от того, откуда запущен валидатор. Привязка к
    каталогу самого файла делает результат воспроизводимым — и честно роняет
    прогон на комплекте, скопированном без соседей (§ 9.3, режим «копия»).

    **Токен приходит из ТЕКСТА заметки, то есть это чужой ввод**, и обращаться
    с ним надо соответственно. Отсюда три ограничения:

    1. **Глоб-метасимволы экранируются.** Строка вида `/*/*/*/*/*/nope.md`
       раскрывалась глобом по всей файловой системе — и заново для каждого
       предка: прогон не заканчивался за минуты. Одна чужая заметка вешала
       проверку целиком, а стандарт рассчитан на заимствование чужих заметок.
    2. **Абсолютные пути и выходы вверх (`..`, `~`) не резолвятся вовсе.**
       Иначе по выводу валидатора можно было выяснять, какие файлы есть на
       чужой машине: `/etc/passwd` молчал (значит, есть), выдуманный путь —
       ругался. Ссылка статуса адресует документ рядом, а не всю ФС.
    3. **Подъём ограничен** — уровнями и границей репозитория (каталог с
       `.git`). Дальше корня проекта искать нечего: там начинается чужое.
    """
    token = (token or "").strip()
    if not token or token.startswith(("/", "~")) or ".." in token.split("/"):
        return False
    escaped = glob.escape(token)
    root = os.path.abspath(file_dir)
    for _ in range(MAX_STATUS_PATH_UP + 1):
        if os.path.exists(os.path.join(root, token)):
            return True
        if glob.glob(os.path.join(root, escaped) + "*"):
            return True
        parent = os.path.dirname(root)
        if os.path.isdir(os.path.join(root, ".git")) or parent == root:
            return False
        root = parent
    return False


def walk_md(root: str):
    """Все `.md` под каталогом, БЕЗ захода в симлинки-каталоги.

    Обход по символическим ссылкам на одной петле (`ln -s . x`) даёт
    комбинаторный взрыв путей: прогон не заканчивается, а один файл
    превращается в десятки «заметок» и ложных дублей.
    """
    out = []
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = [d for d in dirnames if not os.path.islink(os.path.join(dirpath, d))]
        # Расширение сравнивается БЕЗ учёта регистра. `Заметка.MD` — тот же файл: на
        # macOS и Windows файловая система его от `.md` не отличает вовсе, а обход
        # отличал — и заметка выпадала из базы молча, без единой строки в отчёте.
        out.extend(os.path.join(dirpath, fn) for fn in filenames
                   if fn.lower().endswith(".md"))
    return sorted(out)


# ── режим «база по метке» (§ 1 принцип 10, § 9.3 п. 8) ───────────────────────
# Умолчание границы обхода — и оно объявлено вслух, потому что § 9.3 п. 6 требует
# назвать умолчание, а не оставить его в коде. Список короткий намеренно: сюда входит
# только то, что есть у ЛЮБОГО проекта в этой среде, а не то, что встретилось нам.
#   .git, node_modules — служебные деревья инструментов; заметок в них не бывает;
#   .claude            — сам агент, его навыки и хуки. У этих файлов своя шапка
#                        (`name`, `description`), к базе знаний отношения не имеющая.
# Папок конкретных фреймворков и плагинов здесь НЕТ: у чужого проекта их может не быть
# вовсе, а зашитое умолчание молча решало бы за него. Такие папки объявляются самим
# проектом — ключ `validate.base.exclude` в config.yaml.
# `_templates/` и `_personal/` сюда тоже не входят: их отсекает is_excluded() на обоих
# режимах разом, и второй дом этому правилу не нужен.
DEFAULT_WALK_EXCLUDES = (".git", ".claude", "node_modules")


def path_excluded(path: str, root: str, excludes) -> bool:
    """Путь попадает под границу обхода: имя папки в любом колене либо путь-приставка.

    Имя без слэша (`Архив`) значит «папка с таким именем, где бы она ни лежала»:
    иначе человеку пришлось бы перечислять каждое её вхождение. Имя со слэшем
    (`Архив/2024`) — путь от корня обхода: так исключают одно конкретное место,
    не задев тёзок.
    """
    try:
        rel = os.path.relpath(path, root)
    except ValueError:
        rel = path                    # разные диски (Windows) — судим по полному пути
    rel = rel.replace(os.sep, "/")
    parts = rel.split("/")
    for raw in excludes:
        e = str(raw).strip().replace(os.sep, "/").strip("/")
        if not e:
            continue
        if "/" in e:
            if rel == e or rel.startswith(e + "/"):
                return True
        elif e in parts:
            return True
    return False


def classify_by_marker(paths, declared_types, other_types=()):
    """Разложить файлы на заметки и на то, что заметкой быть НЕ смогло (§ 9.3 п. 8).

    Возвращает (заметки, невидимки, безтиповые).

    Зачем разложение, а не один список. В режиме по метке файл, чей `type` не
    опознан, просто не попадает в базу — прогон при этом зелёный, а заметка
    пропала. Это тот самый рецидивный класс: артефакт непроверенного неотличим
    от артефакта чистого (§ 10.1). Поэтому непопавшие возвращаются наравне
    с попавшими, и о каждом говорится вслух:

      • невидимка — шапка есть, а заметкой файл не стал: `type` вне словаря,
        битый YAML, файл не прочитан. Ошибка: любой из трёх случаев — либо
        опечатка в заметке, либо файл, которому в границе обхода не место;
      • безтиповой — шапка есть, ключа `type` нет вовсе. Предупреждение:
        отличить забытый `type` от чужой шапки (скилл, шаблон Obsidian)
        машина не может — это решает человек, один раз, границей обхода.

    Файл БЕЗ шапки не попадает никуда и не считается находкой: в дереве проекта
    таких большинство (README, журналы, документы), и объявлять их поломкой
    значило бы ругаться на весь проект — ровно то, из-за чего режим и заводится.
    """
    # Знанием объявленные типы и НЕ знанием объявленные — оба множества делают файл
    # заметкой. Разница между ними в другом: спрашивать ли с него провенанс. Пока
    # второго множества не было, у карантина § 10.2 в этой раскладке не оставалось
    # выхода: тип, не объявленный знанием, переставал быть заметкой вовсе — то есть
    # рецепт стандарта уводил заметку из базы, а не под предупреждение 14.
    known = ({"knowledge", *CORE_NON_KNOWLEDGE_TYPES}
             | {norm_type(d) for d in declared_types}
             | {norm_type(d) for d in other_types})
    заметки, невидимки, безтиповые = [], [], []
    for p in paths:
        text, problem = read(p)
        if problem and not text:
            невидимки.append((p, "файл не прочитан — значит и не опознан"))
            continue
        строки = text.split("\n")
        if строки[0].strip() != "---":
            # Шапка, сдвинутая вниз пустыми строками, — не «файл без шапки», а сбитая
            # шапка: YAML её не увидит, и файл выпадет из базы. Молчать про это нельзя
            # по той же причине, что и про опечатку в `type`. Признак узкий: до `---`
            # стоят только пустые строки. Строка `---` посреди текста — это
            # горизонтальная линейка, и трогать её нельзя.
            первая = next((i for i, l in enumerate(строки) if l.strip()), None)
            if первая is not None and строки[первая].strip() == "---":
                невидимки.append((p, "шапка начинается не с первой строки — YAML её "
                                     "не читает; убери пустые строки перед `---`"))
            continue
        block, structural = frontmatter_block(text)
        if block is None:
            невидимки.append((p, structural))
            continue
        try:
            data = yaml.load(block, Loader=StrictNoDuplicateLoader)
        except Exception as err:
            невидимки.append((p, f"frontmatter не разобрался ({type(err).__name__})"))
            continue
        if not isinstance(data, dict):
            невидимки.append((p, "frontmatter есть, но это не набор полей"))
        elif "type" not in data:
            безтиповые.append(p)
        elif norm_type(data.get("type")) in known:
            заметки.append(p)
        else:
            невидимки.append((p, f"type: {data.get('type')} — нет ни в словаре ядра, "
                                 f"ни в объявленных доменных типах"
                                 + homoglyph_hint(data.get("type"),
                                                  lambda t: norm_type(t) in known)))
    return sorted(заметки), sorted(невидимки), sorted(безтиповые)


def collect_md(paths):
    """Файлы .md из списка путей (файл — как есть, папка — рекурсивно)."""
    out = []
    for p in paths:
        if os.path.isfile(p):
            out.append(p)
        elif os.path.isdir(p):
            out.extend(walk_md(p))
        else:
            print(f"ОШИБКА: путь --core не найден: {p}")
            sys.exit(2)
    # Фикстуры смоук-теста из --core выведены. Они СЛОМАНЫ НАМЕРЕННО — на них
    # проверяется, что валидатор ловит подсаженную ошибку. Пока их не отсекали,
    # человек, скопировавший комплект вместе с tests/ (таблица § 9.3 объявляет их
    # необязательными, но не запрещает), получал на первом же прогоне красный экран
    # из чужих заготовок — и ни одна из ошибок не была про его базу. Тот же отказ,
    # что у рецепта «потрогать»: первое знакомство с продуктом, у которого «зелёный
    # молчит», не должно начинаться с красного, за которым ничего нет.
    out = [f for f in out if "/tests/fixtures/" not in f.replace(os.sep, "/")]
    return [f for f in out if not any(is_excluded(f, p) for p in paths if f.startswith(p))]


