ZERO_WIDTH_RE = re.compile(r"[\u200b-\u200f\u202a-\u202e\u2060\ufeff]")


# Сводка для режима отчёта (§ 10, «Отчёт: взгляд на базу, а не вердикт»). Заполняется
# ПО ХОДУ обычного прогона из уже посчитанного: отдельного обхода и второго разбора
# frontmatter у отчёта нет намеренно — иначе у тех же чисел завелось бы два дома,
