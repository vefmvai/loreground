#!/usr/bin/env python3
"""Перебор комплекта: где форма возврата зависит от флага, а один из выходов про флаг забыл.

Зачем. Функция, которая по флагу отдаёт то число, то кортеж, — законная конструкция:
`return (n, разбивка) if with_groups else n`. Беда начинается у РАННЕГО выхода. Он пишется
раньше флага и живёт своей жизнью: отдаёт голое число всегда. Вызывающий, попросивший
кортеж, падает на распаковке — `TypeError: cannot unpack non-iterable int object`.

Чем это хуже обычной ошибки. Падает не проверка, а ПРОГОН целиком: человек получает
«прогон не состоялся» вместо названного дефекта и идёт чинить установку вместо своей
заметки. Ловится такое только на входе, которого нет в наборе тестов, — а ранний выход
как раз и стоит на входе-вырожденце (пустой список, ничего не нашлось), который в
фикстурах встречается реже всего.

Правило перебора. Если хотя бы один `return` функции переключает форму по имени параметра
(`X if флаг else Y`, где X и Y разной формы), то и остальные `return` этой функции обязаны
переключаться по тому же имени. Возврат `None` — исключение: это «не знаю», отдельный
законный ответ, а не вторая форма результата.

Как читается вывод: по строке на находку, `путь:строка  что`. Код выхода всегда 0 —
судит вызывающий. Пустой вывод значит «функций с рассогласованным ранним выходом не
встретилось», а не «распаковка нигде не упадёт»: вызов по атрибуту (`модуль.функция()`)
и форма, собранная в переменной, сюда не входят.

Почему разбор синтаксиса, а не поиск по тексту: см. `enc-sweep.py` — там та же причина
сказана целиком, здесь указатель.
"""
import ast
import os
import sys


def форма(узел):
    """Форма возвращаемого значения: 'none' | 'scalar' | число элементов кортежа."""
    if узел is None or (isinstance(узел, ast.Constant) and узел.value is None):
        return "none"
    if isinstance(узел, (ast.Tuple, ast.List)):
        return len(узел.elts)
    return "scalar"


def имена(узел):
    """Имена переменных, упомянутые в условии."""
    return {n.id for n in ast.walk(узел) if isinstance(n, ast.Name)}


def свои_return(функция):
    """`return` этой функции, без вложенных: у вложенной функции контракт свой."""
    чужие = {
        n
        for f in ast.walk(функция)
        if isinstance(f, (ast.FunctionDef, ast.AsyncFunctionDef)) and f is not функция
        for n in ast.walk(f)
    }
    return [
        n for n in ast.walk(функция)
        if isinstance(n, ast.Return) and n not in чужие
    ]


def параметры(функция):
    a = функция.args
    return {p.arg for p in a.posonlyargs + a.args + a.kwonlyargs}


def разобрать(функция):
    """(флаги-переключатели, выходы) — выход это (строка, форма, набор флагов)."""
    флаги, выходы = set(), []
    пар = параметры(функция)
    for r in свои_return(функция):
        v = r.value
        if isinstance(v, ast.IfExp):
            f1, f2 = форма(v.body), форма(v.orelse)
            по = имена(v.test) & пар
            if f1 != f2 and по:
                флаги |= по
                выходы.append((r.lineno, {f1, f2}, по))
                continue
        выходы.append((r.lineno, {форма(v)}, set()))
    return флаги, выходы


def перебор(пути):
    находки = []
    for путь in пути:
        with open(путь, encoding="utf-8") as ф:
            текст = ф.read()
        try:
            дерево = ast.parse(текст, путь)
        except SyntaxError:
            continue
        for функция in ast.walk(дерево):
            if not isinstance(функция, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            флаги, выходы = разобрать(функция)
            if not флаги:
                continue
            for строка, формы, по in выходы:
                if по & флаги:
                    continue
                if формы == {"none"}:
                    continue
                находки.append(
                    f"{путь}:{строка}  выход функции {функция.name}() отдаёт одну форму "
                    f"({', '.join(sorted(map(str, формы)))}), а другой её выход "
                    f"переключает форму по {', '.join(sorted(флаги))}"
                )
    return находки


def main(аргументы):
    пути = []
    for a in аргументы or ["."]:
        if os.path.isfile(a):
            пути.append(a)
            continue
        for корень, папки, файлы in os.walk(a):
            папки[:] = [p for p in папки if p != "__pycache__"]
            пути += [os.path.join(корень, f) for f in файлы if f.endswith(".py")]
    for строка in перебор(sorted(пути)):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
