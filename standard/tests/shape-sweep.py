#!/usr/bin/env python3
"""Перебор комплекта: где форма возврата зависит от флага, а ранний выход про флаг забыл.

Зачем. Функция, которая по флагу отдаёт то число, то кортеж, — законная конструкция.
Беда начинается у РАННЕГО выхода. Он пишется раньше флага и живёт своей жизнью: отдаёт
голое число всегда. Вызывающий, попросивший кортеж, падает на распаковке —
`TypeError: cannot unpack non-iterable int object`.

Чем это хуже обычной ошибки. Падает не проверка, а ПРОГОН целиком: человек читает
«проверка не выполнена» там, где на деле битые данные. Ловится такое только на входе,
которого нет в наборе тестов, — а ранний выход как раз и стоит на входе-вырожденце
(пустой список, ничего не нашлось), который в фикстурах встречается реже всего.

Правило перебора. Параметр считается **переключателем формы**, если возвраты, зависящие
от него, отдают не те формы, что возвраты, от него не зависящие. Зависимость считается
двумя способами, и оба нужны — один и тот же дефект пишут и так и так:

    return (n, разбивка) if with_groups else n      # выражением
    if with_groups: return n, разбивка              # оператором
    return n

Находка — возврат с определённой формой, который от переключателя НЕ зависит и стоит
**раньше** первого зависящего. Раньше — потому что именно ранний выход и забывает про
флаг; возврат после него это законная вторая половина развилки, и краснеть на ней
значило бы краснеть на исправном коде.

Возврат `None` — объявленное исключение: это «не знаю», отдельный законный ответ
(так им пользуется `parse_month`), а не вторая форма результата.

Как читается вывод: по строке на находку, `путь:строка  что`. Код выхода всегда 0 —
судит вызывающий.

**Что доказывает пустой вывод, а что нет.** Он значит «функций с рассогласованным ранним
выходом не встретилось». Не значит «распаковка нигде не упадёт»: перебор смотрит функции,
а не места вызова, и потому не видит ни распаковки результата чужой функции (импортированной
или вызванной через атрибут модуля), ни формы, собранной в переменную и возвращённой ею.
Зависимость через `and`/`or` и через переменную, вычисленную из флага, он тоже не читает.

Чего пустой вывод НЕ скрывает: файл, который не прочитался или не разобрался, назван
отдельной строкой. Молчаливый пропуск такого файла делал бы ноль находок неотличимым от
ноля дефектов — то есть перебор болел бы ровно тем, что ищет.

Почему разбор синтаксиса, а не поиск по тексту: см. `enc-sweep.py` — там та же причина
сказана целиком, здесь указатель.
"""
import ast
import os
import sys


def форма(узел):
    """Форма возвращаемого значения: 'none' | 'scalar' | число элементов кортежа."""
    if узел is None or (isinstance(узел, ast.Constant) and узел.value is None):
        return "none"
    if isinstance(узел, (ast.Tuple, ast.List)):
        return len(узел.elts)
    return "scalar"


def имена(узел):
    """Имена переменных, упомянутые в выражении."""
    return {n.id for n in ast.walk(узел) if isinstance(n, ast.Name)}


def параметры(функция):
    a = функция.args
    return {p.arg for p in a.posonlyargs + a.args + a.kwonlyargs}


def выходы(функция, пар):
    """[(строка, {формы}, {параметры, от которых возврат зависит})].

    Обход ручной, а не `ast.walk`: нужен СТЕК объемлющих `if`, а walk порядок вложенности
    теряет. Вложенные функции не спускаются — у них свой контракт.
    """
    собрано = []

    def спуск(узлы, стек):
        for узел in узлы:
            if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda,
                                 ast.ClassDef)):
                continue
            if isinstance(узел, ast.Return):
                значение = узел.value
                зависит = set(стек)
                формы = {форма(значение)}
                if isinstance(значение, ast.IfExp):
                    ф1, ф2 = форма(значение.body), форма(значение.orelse)
                    if ф1 != ф2:
                        зависит |= имена(значение.test) & пар
                    формы = {ф1, ф2}
                собрано.append((узел.lineno, формы, зависит))
                continue
            if isinstance(узел, ast.If):
                новый = стек | (имена(узел.test) & пар)
                спуск(узел.body, новый)
                спуск(узел.orelse, новый)
                continue
            for поле, значение in ast.iter_fields(узел):
                if isinstance(значение, list):
                    спуск([v for v in значение if isinstance(v, ast.AST)], стек)
                elif isinstance(значение, ast.AST):
                    спуск([значение], стек)

    спуск(функция.body, frozenset())
    return собрано


def разбор(функция):
    """Находки одной функции: [(строка, {формы}, переключатель)]."""
    пар = параметры(функция)
    все = выходы(функция, пар)
    if len(все) < 2:
        return []
    найдено = {}
    for флаг in sorted({p for _, _, з in все for p in з}):
        зависимые = [в for в in все if флаг in в[2]]
        прочие = [в for в in все if флаг not in в[2]]
        if not зависимые or not прочие:
            continue
        # `None` из сравнения форм выброшен на ОБЕИХ сторонах, а не только у находки.
        # Он объявлен «не знаю», то есть не формой результата, — и пока он считался
        # формой, честная функция с `return None` среди прочих выглядела переключателем
        # и краснела. Страж, шумящий на исправном коде, выключается человеком.
        формы_зависимых = set().union(*(в[1] for в in зависимые)) - {"none"}
        формы_прочих = set().union(*(в[1] for в in прочие)) - {"none"}
        if not формы_зависимых or not формы_прочих:
            continue  # сравнивать не с чем: одна из сторон говорит только «не знаю»
        if формы_зависимых == формы_прочих:
            continue  # параметр форму не переключает — это обычное ветвление
        первый = min(в[0] for в in зависимые)
        for строка, формы, _ in прочие:
            if строка >= первый or формы == {"none"}:
                continue
            найдено.setdefault(строка, (формы, флаг))
    return [(с, ф, фл) for с, (ф, фл) in sorted(найдено.items())]


def перебор(пути):
    находки = []
    for путь in пути:
        # Файл, который не прочитался или не разобрался, — это НЕ «в нём чисто».
        # Молчаливый пропуск делал пустой вывод перебора неотличимым от пройденного:
        # подложенный синтаксически битый файл давал ноль находок и зелёный смоук.
        # Тот самый класс, ради которого этот перебор и заведён (§ 10.1).
        try:
            with open(путь, encoding="utf-8") as ф:
                текст = ф.read()
        except (OSError, UnicodeDecodeError) as err:
            находки.append(f"{путь}:1  файл не прочитан ({type(err).__name__}) — "
                           f"проверить нечем")
            continue
        try:
            дерево = ast.parse(текст, путь)
        except SyntaxError as err:
            находки.append(f"{путь}:{err.lineno or 1}  код не разобрался ({err.msg}) — "
                           f"проверить нечем")
            continue
        for функция in ast.walk(дерево):
            if not isinstance(функция, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for строка, формы, флаг in разбор(функция):
                находки.append(
                    f"{путь}:{строка}  ранний выход функции {функция.name}() отдаёт форму "
                    f"({', '.join(sorted(map(str, формы)))}) всегда, а форму этой функции "
                    f"переключает параметр {флаг} — вызов с ним упадёт на распаковке"
                )
    return находки


def main(аргументы):
    пути = []
    for a in аргументы or ["."]:
        if os.path.isfile(a):
            пути.append(a)
            continue
        for корень, папки, файлы in os.walk(a):
            папки[:] = [p for p in папки if p != "__pycache__"]
            пути += [os.path.join(корень, f) for f in файлы if f.endswith(".py")]
    for строка in перебор(sorted(пути)):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
