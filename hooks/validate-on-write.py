#!/usr/bin/env python3
"""Автопрогон валидатора после записи в базу: событие PostToolUse.

`core.md` § 11 п. 12 требует прогон после каждого ввода знания. Требование адресовано
модели, то есть исполняется, «если она не отвлеклась»: заметка записана — прогон забыт —
ошибка живёт до следующей ревизии. Здесь прогон делает код.

Что важно в поведении:
  • зелёный прогон молчит — «ошибок нет» это не новость, а расход контекста;
  • красный прогон приезжает целиком, сразу после записи, пока автор ещё в теме;
  • «прогон не состоялся» (код 2) говорится отдельно от «чисто»;
  • команда берётся из `config.yaml` пользователя — та же комплектация, что и при ручном
    прогоне (§ 9.3 п. 7). Своей команды хук не придумывает: придуманная отличалась бы
    флагами и давала бы другой ответ, чем ручной прогон.

**Чего этот хук не видит, и это надо знать сразу.** Он срабатывает на записи ИНСТРУМЕНТАМИ
агента (`Write`, `Edit`, `MultiEdit`, `NotebookEdit`). Правка заметки из терминала — `sed`,
`cat >`, `perl -pi`, — как и правка руками в редакторе, для него не существует: событие
`PostToolUse` на них не приходит. Молчание хука при этом неотличимо от «база чиста», и
человек, чинивший базу шеллом, час считает, что проверка его одобряет. Расширить ворота
на `Bash` нельзя дёшево: хук срабатывал бы на каждой команде, а прогон базы стоит секунды.
Поэтому граница названа, а не закрыта: **после правок мимо инструментов агента прогон
запускается руками.**

Одна оговорка к последнему пункту, и её лучше знать заранее. Совпадают КОМАНДА и её
флаги, а не обязательно тот файл, до которого команда доводит. Голое имя вроде
`lore-validate` человек в терминале разрешает через `PATH` — то есть в УСТАНОВЛЕННЫЙ
комплект; хук, у которого этого `PATH` нет, берёт обёртку своего комплекта. Пока комплект
на машине один, это одно и то же. Когда их два (обновление на подходе, запуск с
`--plugin-dir`, клон репозитория рядом), ручной прогон и автопрогон могут пойти разными
версиями валидатора — и разойтись вердиктом, ничего об этом не сказав. Своего `PATH` хук
завести не может: это и есть та зависимость от среды, из-за которой он молчал вовсе.
"""
import json
import os
import shlex
import shutil
import subprocess
import sys
import time

# Помощники комплекта, дом у каждого один: печать строки в контекст и ответ на свою
# поломку. Лежат рядом со скриптом, поэтому путь к ним — от собственного файла.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _out import сказать  # noqa: E402
from _broken import сломался  # noqa: E402

MARKER = ".loreground"
CONFIG = "config.yaml"
WRITERS = ("Write", "Edit", "MultiEdit", "NotebookEdit")
HEAD = "Loreground, проверка базы после записи"
CAP = 4000
SLOW = 5.0


def emit(message):
    сказать("PostToolUse", message)
    sys.exit(0)


def _под(parent, child):
    """Одно сравнение «child внутри parent» через относительный путь.

    Через `relpath`, а не `startswith(parent + os.sep)`: у корня файловой системы
    `parent` уже кончается разделителем, склейка даёт `//`, и совпадения нет ни у
    одного пути. `under("/", "/tmp/x.md")` отвечал **False** — то есть на законном
    значении сравнение давало неверный ответ, а неверный ответ здесь означает
    молчание хука, читаемое как «чисто».
    """
    try:
        rel = os.path.relpath(child, parent)
    except ValueError:
        return False                  # Разные диски на Windows — не «под» по определению.
    return rel == os.curdir or not (rel == os.pardir or rel.startswith(os.pardir + os.sep))


def under(parent, child):
    """Лежит ли `child` внутри `parent`. Сомнение решается в пользу «да».

    Считается ЧЕТЫРЬМЯ заходами, и все четыре — в дешёвую сторону: лишний прогон
    стоит секунд, пропущенный молчит и выглядит чистым.

      • путь как есть и путь, разрешённый от симлинков. Только `realpath` было
        мало: папку базы часто держат символической ссылкой наружу (хранилище
        Obsidian, общий диск), и разрешённый путь «уезжает» из проекта — хук
        замолкал навсегда, хотя обход валидатора такой корень как раз проходит;
      • без учёта регистра. На macOS и Windows файловая система регистр не различает,
        а сравнение строк различает: `Knowledge` из конфига и `knowledge` на диске —
        одна папка для ОС и две разные для сравнения. `os.path.normcase` здесь НЕ
        помогает: на macOS и Linux это тождественная функция.
    """
    свои = {os.path.abspath(parent), os.path.realpath(parent)}
    чужие = {os.path.abspath(child), os.path.realpath(child)}
    if any(_под(p, c) for p in свои for c in чужие):
        return True
    return any(_под(p.casefold(), c.casefold()) for p in свои for c in чужие)


def валидатор_комплекта():
    """Модуль валидатора, лежащего рядом с этим хуком. Не достался — None.

    Загружается по адресу от собственного файла, а не импортом по имени: `standard/` —
    не пакет и в `sys.path` не лежит.

    **Чем он может быть не тем валидатором, которым прогоняют.** В режиме «копия»
    прогон идёт локальной копией из проекта, а сюда приезжает комплектный — версии
    могут отличаться. Берётся он ради разборов, у которых один дом (§ 6): что
    значит строка в `exclude` и как приводится значение ключа. Повторить их здесь
    значило бы завести второй дом правилу, и разъехались бы они молча.

    Не достался — решение о границе не принимается вовсе, и прогон случается.
    Единственный честный ответ на «не смог разобрать границу»: молчание хука по его
    же устройству значит «чисто», поэтому любая неудача обязана падать в прогон.
    """
    адрес = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                         "standard", "validate.py")
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location("_lore_validate_гра", адрес)
        модуль = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(модуль)
        return модуль
    except Exception:
        return None


def база_за_границей(обход, excludes, path_excluded):
    """Осталась ли в границе хоть одна заметка. Пусто — сужать НЕЛЬЗЯ.

    Сужение «эта правка не про базу» законно ровно тогда, когда граница прочитана
    и что-то в базе оставляет. Три случая, где это не так, и каждый кончался вечным
    молчанием хука при том, что руками та же команда кричит кодом 2:

      • корня обхода нет на диске (опечатка в `base.root`, `~` в значении,
        переименованная папка);
      • `exclude` перечислил все папки базы;
      • корень есть, а заметок под ним нет вовсе.

    Перебор останавливается на ПЕРВОМ подходящем файле, поэтому на здоровой базе
    он стоит один каталог, а не обход целиком. Дорого он обходится только там, где
    база и правда пуста, — то есть в том самом случае, ради которого заведён.

    Обход ОБЯЗАН лежать внутри проекта, и проверяет это вызывающий. Без границы
    `root: /` пускал перебор по всей файловой системе: на каждой записи в файл —
    обход диска. Проверка, которая стоит минуты, будет выключена в первый же день,
    а выключенный сторож хуже отсутствующего.
    """
    if not os.path.isdir(обход):
        return False
    for dirpath, dirnames, filenames in os.walk(обход, followlinks=False):
        for fn in filenames:
            if fn.lower().endswith(".md"):
                if not path_excluded(os.path.join(dirpath, fn), обход, excludes):
                    return True
    return False


def main():
    try:
        event = json.load(sys.stdin)
    except (ValueError, OSError):
        return  # Без входа судить не о чем; сорвать работу инструмента нельзя.

    if event.get("tool_name") not in WRITERS:
        return

    project = os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or os.getcwd()
    # Ворота комплекта. Метка — обычный ФАЙЛ: папка с таким именем меткой не считается.
    # `isfile`, а не `exists`, — потому что ворота у всех хуков комплекта объявлены одни
    # (`hooks.json`), и разъезд на краю уже случался: `mkdir .loreground` глушил ровно
    # двух сторожей, пока двое других продолжали говорить. Агент выглядел оснащённым,
    # а слежение за версиями было мертво.
    if not os.path.isfile(os.path.join(project, MARKER)):
        return

    path = (event.get("tool_input") or {}).get("file_path") or ""
    # Расширение сравнивается БЕЗ учёта регистра — тем же правилом, что у обхода
    # валидатора (`walk_md`): на macOS и Windows `Заметка.MD` и `заметка.md` — один
    # файл для файловой системы. Пока правило стояло здесь с учётом регистра, у него
    # было два дома, и разъезд выражался тишиной: валидатор считал файл заметкой и
    # печатал про него находки, а хук на запись в него молчал.
    if not path.lower().endswith(".md") or not under(project, path):
        return

    config_path = os.path.join(project, CONFIG)
    if not os.path.exists(config_path):
        return  # Комплектация не объявлена — своей команды хук не придумывает.

    try:
        import yaml
    except ImportError:
        # Отдельно от разбора: без PyYAML прогон не состоится НИКОГДА, а стартовый хук
        # говорит про паспорт и о мёртвой проверке записи не сообщает.
        # Интерпретатор называется свой — см. тот же довод в startup-load.py: `pip` без
        # уточнения кладёт библиотеку в тот Python, который первым отзовётся, а хук зовут
        # строкой `python3` из hooks.json, и это бывает другой.
        emit(HEAD + ": PyYAML не установлен — комплектацию прогона прочитать нечем. "
             "Проверка после записи НЕ выполнена, и это не «чисто». Установить именно в этот "
             "интерпретатор: " + sys.executable + " -m pip install pyyaml")

    try:
        with open(config_path, encoding="utf-8") as handle:
            config = yaml.safe_load(handle) or {}
    except Exception as err:
        # Прежде здесь стоял тихий выход с доводом «разбор конфига — забота стартовых
        # хуков». Довод верен наполовину: стартовый хук и правда об этом кричит, но
        # работает он на СТАРТЕ СЕССИИ. Конфиг ломают посреди работы — и до конца сессии
        # автопрогон мёртв, а его молчание по устройству значит «чисто». Передача
        # ответственности другому хуку законна только тогда, когда тот успеет сказать.
        emit(HEAD + ": " + CONFIG + " не разбирается (" + type(err).__name__ + ") — "
             "комплектацию прогона прочитать нечем. Проверка после записи НЕ выполнена, "
             "и это не «чисто». Почини файл; до этого проверяй базу руками.")

    # Ключ `validate` НЕ проверяется на форму намеренно. Кривая форма (`validate: строка`)
    # роняет обращение ниже, падение ловит общий перехват внизу файла, и хук говорит о
    # своей поломке вслух. Проверка формы с тихим `return` выглядела бы аккуратнее и была
    # бы хуже: молчание хука по его же устройству значит «чисто», то есть громкая поломка
    # превратилась бы в ложный зелёный — ровно тот класс, против которого заведён код 2.
    validate_cfg = config.get("validate") or {}
    # А вот у `base` тихий откат законен, и разница здесь настоящая: без этого ключа хук
    # работал пятнадцать версий и определяет базу по словам команды. Кривой `base` отнимает
    # уточнение границы, но не отнимает прогон — дальше по коду он всё равно случится.
    base_cfg = validate_cfg.get("base") if isinstance(validate_cfg, dict) else None
    if not isinstance(base_cfg, dict):
        base_cfg = {}

    command = (validate_cfg.get("command") or "").strip()
    if not command:
        # Своей команды хук не придумывает намеренно (§ 9.3 п. 7: у комплектации прогона
        # один дом — конфиг, и придуманная команда отличалась бы от ручной флагами).
        # Но молчать об этом нельзя: молчание хука по его же устройству значит «чисто»,
        # и без этой строки автопрогон был мёртв, а выглядел работающим. «Не смог» и
        # «всё в порядке» — разные ответы; здесь именно «не смог».
        emit(HEAD + ": в " + CONFIG + " нет строки validate.command — прогонять нечем. "
             "Проверка после записи НЕ выполняется, и это не «чисто». Допиши команду "
             "прогона в конфиг; она же должна совпадать с той, которой ты проверяешь базу руками.")

    try:
        argv = shlex.split(command)
    except ValueError:
        emit(HEAD + ": команда из " + CONFIG + " не разбирается: " + command[:200])
    if not argv:
        return

    # Имя команды берётся ДО раскрытия `~` и до подстановки адреса — то есть ровно так,
    # как человек написал его в конфиге. Оно звучит во всех сообщениях о беде: чинить он
    # будет свою строку, а не наш путь, и домашний каталог заодно не уезжает в контекст
    # сессии. Прежде имя снималось после `expanduser`, и на `command: ~/bin/чего-нет`
    # хук отвечал раскрытым `/Users/…/bin/чего-нет` — обещание комментария расходилось
    # с поведением на первой же строке.
    #
    # Это про СООБЩЕНИЯ О ПРОГОНЕ, и обещать больше нельзя: когда падает сам хук, ответ
    # о поломке (`_broken.py`) называет полный путь до скрипта намеренно — им человек
    # прогоняет хук руками, и без пути совет неисполним (решение 2026-08-03).
    имя = argv[0]

    # `~` разворачивается здесь, потому что дальше команда идёт БЕЗ оболочки. Человек
    # пишет в конфиг ту команду, которой проверяет базу руками, — так велит § 9.3 п. 7, —
    # а руками он набирает её в терминале, где `~` домашнюю папку раскрывает оболочка.
    # Тильда, доехавшая до `subprocess` как есть, становится обычной папкой с таким
    # именем, и прогон падает «файла нет». Ошибка при этом называется вслух (код 2), но
    # причина у неё нелепая, а починка неочевидная: команда-то рабочая.
    argv = [os.path.expanduser(слово) for слово in argv]

    # Команду комплекта хук ищет РЯДОМ С СОБОЙ, а не в `PATH`. Причина: папку `bin/`
    # комплекта Claude Code дописывает в `PATH` только своей оболочке Bash, а хук —
    # отдельный процесс, и команда зовётся без оболочки (`shell=False`). Поэтому
    # `lore-validate` — каноническая команда режима «указатель» (§ 9.3 п. 7) — из хука
    # не находилась НИКОГДА: автопрогон у такого агента был мёртв с первого дня, а
    # выглядел живым, потому что та же строка в терминале работает.
    #
    # Адрес берётся от собственного файла, а не из `CLAUDE_PLUGIN_ROOT`: переменную
    # кладёт в среду хост, и полагаться на неё — значит чинить одну зависимость от
    # среды другой. Свой путь скрипту известен всегда.
    #
    # Три границы, и каждая из них — отдельная беда, если её снять:
    #   • `PATH` сильнее: команда, которая в `PATH` есть, берётся оттуда. Иначе наш
    #     одноимённый файл молча перебивал бы чужую рабочую команду;
    #   • подменяется только голое имя. В слове со слэшем человек назвал адрес сам,
    #     и подставлять вместо него свой — значит прогнать не то, что он просил;
    #   • подменяется только имя, под которым в `bin/` правда лежит исполняемый файл.
    #     Опечатка в чужой команде обязана остаться видимой: молчаливая подмена похожим
    #     дала бы отчёт о прогоне, которого человек не заказывал.
    разделители = [s for s in (os.sep, os.altsep) if s]
    if shutil.which(argv[0]) is None and not any(s in argv[0] for s in разделители):
        свой = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "bin", argv[0])
        if os.path.isfile(свой) and os.access(свой, os.X_OK):
            argv[0] = свой

    # Раскладка «по метке» (§ 9.3 п. 8): границу задаёт ключ `validate.base`, а не слова
    # команды — имени папки в ней нет вовсе. Пока хук читал только команду, он у такого
    # агента прогонял базу на КАЖДОЙ правке подряд, включая пути, исключённые из базы
    # явно: рабочие папки инструментов проекта и личный слой `my/` — то есть
    # почти всё, что человек правит за день.
    #
    # ЗАКОН ЭТОЙ ВЕТКИ, и он один на все её случаи: **сузить «эта правка не про базу»
    # можно только тогда, когда граница ПРОЧИТАНА и что-то в базе оставляет.** Первая
    # редакция закона не имела и сужала всегда — отчего опечатка в `root`, `~` в его
    # значении и `exclude`, перечисливший все папки базы, глушили хук НАВСЕГДА: руками
    # та же команда кричала кодом 2, а хук молчал, и молчание читалось как «чисто».
    #
    # Что значит строка в `exclude` и как приводится значение ключа — решает не этот файл:
    # оба разбора берутся у валидатора (`path_excluded`, `norm_type`). У правила «имя без
    # слэша значит папку где угодно, со слэшем — путь от корня» один дом (§ 6); своя
    # копия разошлась бы молча — так и вышло с приведением значения: собственный `norm`
    # не снимал кавычек, и `mode: '"marker"'` читался двумя сторонами по-разному.
    валидатор = валидатор_комплекта() if base_cfg else None
    if валидатор is not None and валидатор.norm_type(base_cfg.get("mode")) == "marker":
        обход = os.path.join(project, str(base_cfg.get("root") or ".").strip() or ".")
        excludes = (list(валидатор.DEFAULT_WALK_EXCLUDES)
                    + [str(x) for x in (base_cfg.get("exclude") or [])])
        # Первенство источников берётся у валидатора, а не назначается заново: там
        # (`validate.py`, разбор `validate.base`) **названная в команде папка отменяет
        # `root` из конфига**. Пока хук брал `root` всегда, у факта «где база» стало три
        # дома — `base.root`, слово команды и запасная ветка ниже, — и расходились они
        # тишиной. Команда папку назвала: границу задаёт она, `base.root` не спрашиваем.
        названа = any(os.path.isdir(os.path.join(project, t))
                      for prev, t in zip(argv, argv[1:])
                      if not t.startswith("-") and not prev.startswith("-"))
        # Корень обхода вне проекта — не наше дело судить: сужать нельзя, и перебор туда
        # не пускается. `root: /` иначе означал бы обход всей файловой системы на каждой
        # записи; проверка ценой в минуты выключается в первый же день.
        свой_обход = under(project, обход)
        if not названа and свой_обход and база_за_границей(обход, excludes, валидатор.path_excluded):
            if not under(обход, path):
                return      # Файл вне корня обхода: валидатор его и не увидит.
            if валидатор.path_excluded(path, обход, excludes):
                return      # Путь исключён из базы решением проекта, а не нашей догадкой.

    # Прогон запускается только если изменённый файл лежит в проверяемой базе. Папки берём
    # из самой команды — второго дома у них не заводим. Не распознались — прогоняем всё
    # равно: лишний прогон дешевле молчаливого пропуска.
    #
    # Смотрятся ВСЕ слова без дефиса, а не последнее. Последним оказывается значение флага:
    # каноническая команда режима «копия» (§ 9.3 п. 7, `skills/init/SKILL.md` шаги 7 и 9) —
    # `validate.py knowledge --core standard`, и по прежнему правилу хук объявлял базой
    # `standard/`, а запись в `knowledge/` — не своим делом. Молчал он при этом ровно так
    # же, как на чистой базе: автопрогон был мёртв у каждого, кто взял команду из доки.
    # Разбор флагов по списку эту беду не лечит — ошибка в списке снова даёт тишину.
    #
    # Пропуск разрешён только в одном случае: база в команде НАЗВАНА и файл не под ней.
    # Названной считается папка, перед которой не стоит флаг. Без этого различения
    # пропуск возвращался двумя путями, и оба кончались тишиной: команда `validate.py
    # --core standard` базу не называет вовсе (валидатор берёт `knowledge` по умолчанию),
    # а `validate.py kknowledge --core standard` называет её с опечаткой — в обоих случаях
    # распознавалось только значение флага, и запасной выход «не распозналось — прогоняем»
    # выключался им же. Регистр сравнивается через `normcase`: на macOS и Windows папка
    # `Knowledge` из конфига и `knowledge` на диске — одна и та же папка для файловой
    # системы и две разные для сравнения строк.
    named = [os.path.join(project, t) for prev, t in zip(argv, argv[1:])
             if not t.startswith("-") and not prev.startswith("-")]
    dirs = [os.path.join(project, t) for t in argv[1:] if not t.startswith("-")]
    dirs = [d for d in dirs if os.path.isdir(d)]
    if any(os.path.isdir(d) for d in named) and not any(under(d, path) for d in dirs):
        return

    # Кодировка названа явно с ОБЕИХ сторон, а не взята у системы. Прежнее `text=True`
    # расшифровывало ответ прогона по локали: на русской Windows это cp1251, а валидатор
    # печатает UTF-8 со значками — расшифровка падала внутри чтения, `subprocess` при этом
    # не падал и отдавал пустой stdout. Отчёт пропадал ЦЕЛИКОМ, а шапка «найдены проблемы»
    # оставалась: агенту говорили «чини сейчас», не сказав что. Это тот же класс подмены,
    # против которого заведён код 2, только исход выглядит содержательным.
    #
    # Дочернему процессу кодировка вывода назначается тем же заходом. Без этого он берёт её
    # у той же локали, и одностороннее «читать как UTF-8» превратило бы кириллицу отчёта
    # в мусор на каждой русской Windows — починка одного входа ценой нового.
    # `errors="replace"` — последний рубеж: команду прогона пишет пользователь, чужой скрипт
    # отдаёт что угодно, и испорченный знак в отчёте дешевле потерянного отчёта.
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    started = time.time()
    try:
        run = subprocess.run(argv, cwd=project, capture_output=True, timeout=120,
                             encoding="utf-8", errors="replace", env=env)
    except FileNotFoundError:
        emit(HEAD + ": команда «" + имя + "» не найдена. Прогон не состоялся — это не «чисто».")
    except subprocess.TimeoutExpired:
        emit(HEAD + ": прогон не уложился в 120 с и снят. Это не «чисто».")
    except OSError as err:
        # Всё остальное, чем ОС отвечает на «запусти»: нет бита +x (PermissionError),
        # битый интерпретатор в шебанге, слишком длинный аргумент. Раньше это уходило
        # в общий перехват внизу файла и означало молчание, неотличимое от зелёного.
        emit(HEAD + ": команда «" + имя + "» не запустилась — " + type(err).__name__
             + ": " + str(err)[:120] + ". Прогон не состоялся, это не «чисто».")
    spent = time.time() - started

    if run.returncode == 0:
        return  # Зелёный молчит.

    output = ((run.stdout or "") + (run.stderr or "")).strip()
    if len(output) > CAP:
        output = output[:CAP] + "\n… отчёт обрезан; полный — прогнать команду вручную."

    # «Найдены проблемы» говорится ТОЛЬКО на код 1. Валидатор объявляет три исхода
    # (§ 10: 0 — чисто, 1 — проблемы, 2 — прогон не состоялся), и всё, что вне этих трёх,
    # пришло не от него: 127 — оболочка не нашла команду в скрипте-обёртке, отрицательное —
    # процесс убит сигналом, прочее — чужой скрипт со своей таксономией. Прежде такой ответ
    # объявлялся находкой в базе, и агента отправляли чинить базу, которую никто не
    # проверял, — ровно тот класс подмены, против которого заведён код 2.
    #
    # Пустой вывод при коде 1 — отдельный ответ, а не «проблемы без подробностей». «Найдены
    # проблемы, разбери сейчас» без единой строки отправляет агента чинить базу, не сказав
    # что: за таким кодом может не стоять ни одной выполненной проверки. Это та же подмена,
    # что уже вылечена ниже для кодировки («шапка осталась, отчёт пропал»), — вход другой,
    # исход тот же.
    if run.returncode == 1 and not output:
        head = (HEAD + ": команда ответила кодом 1, но не напечатала НИЧЕГО. Что именно"
                " не так с базой — неизвестно, и это не «найдены проблемы»: проверь"
                " команду прогона в " + CONFIG + " и прогони её руками.")
    elif run.returncode == 1:
        head = HEAD + ": найдены проблемы (код 1). Разбери их сейчас, пока правка свежая."
    elif run.returncode == 2:
        head = HEAD + ": прогон НЕ СОСТОЯЛСЯ (код 2). Это не «база чистая» — проверка не выполнена."
    else:
        head = (HEAD + ": прогон ответил кодом " + str(run.returncode) + ", а такого исхода у "
                "валидатора нет (есть 0, 1, 2). Прогон НЕ СОСТОЯЛСЯ — это не «чисто» и не "
                "«найдены проблемы»: чинить надо команду прогона, а не базу.")

    tail = ""
    if spent > SLOW:
        tail = ("\n\nПрогон занял " + str(round(spent, 1)) + " с: инкрементального режима нет, "
                "проверяется вся база. На большой базе это налог на каждую запись.")

    emit(head + "\n\n" + output + tail)




if __name__ == "__main__":
    try:
        main()
    except Exception as err:
        сломался("validate-on-write.py", err, "PostToolUse")
    sys.exit(0)
