#!/usr/bin/env python3
"""Сторож расхождения версий: событие SessionStart.

Агент собран на какой-то версии комплекта, и это записано в метке `.loreground`
полем `собран_на_версии`. Комплект на машине живёт своей жизнью и обновляется. Этот
сторож называет расхождение вслух — потому что обновление агента под новую версию
стандарта обязано быть **осознанным действием**, а не тем, что случается само
(core.md § 9.3).

Почему отдельный файл, а не ветка в codex-freshness.py. Факты разные, и вердикт у
каждого свой: кодекс меняется не в каждом релизе, поэтому «кодекс совпал» и «версия
стандарта совпала» — не одно утверждение. Сторож кодекса обязан молчать ровно тогда,
когда с кодексом всё в порядке; вшить в него второй факт значит сделать его молчание
двусмысленным, а молчание здесь — самый дорогой из исходов, его читают как «всё в
порядке». Цена решения названа честно: это четвёртый файл и ещё один хук на старте.

Исходы:
  • комплекта на машине нет      — молчит. Это ШТАТНОЕ состояние увезённого агента:
                                   сравнивать не с чем и обновляться неоткуда;
  • комплект есть, версии совпали — молчит;
  • комплект есть, версии разошлись — называет обе и говорит, что делать;
  • комплект есть, а версия сборки не записана — говорит именно это: отследить
                                   расхождение нечем, и это не «всё в порядке».

Честная граница. Сверяются **номера версий, а не тексты**: локальную правку ядра на
месте этот сторож не увидит и увидеть не может. Дом версии сборки один — метка (§ 9.3
п. 6), поэтому больше сторож нигде её и не ищет.
"""
import json
import os
import re
import sys

# Помощники комплекта, дом у каждого один: печать строки в контекст и ответ на свою
# поломку. Лежат рядом со скриптом, поэтому путь к ним — от собственного файла.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _out import сказать  # noqa: E402
from _broken import сломался  # noqa: E402

MARKER = ".loreground"
# Класс пробелов — ГОРИЗОНТАЛЬНЫЙ, не `\s`. `\s` включает перевод строки, и при пустом
# значении поля выражение перешагивало на следующую строку метки, забирая её как версию:
# соседняя строка — это `собран: <дата>`, то есть сторож, чья работа не дать выдумать
# версию, сам подставлял дату и велел агенту сказать это человеку. Ровно та подделка
# провенанса, против которой он написан.
BUILT_ON_RE = re.compile(r"^[ \t]*собран_на_версии[ \t]*:[ \t]*(.+?)[ \t]*$", re.M)
# Значение, которое навык сборки пишет, когда манифест прочитать не удалось. Считается
# отсутствием версии, а не версией с таким именем.
UNKNOWN = "неизвестна"
# Режим подключения — тоже факт сборки, и дом у него тот же, что у версии: метка.
# Раньше он не записывался никуда, и сторож выводил его из наличия папки standard/ —
# то есть у факта не было дома в стандарте, чья центральная норма «у факта один дом».
MODE_RE = re.compile(r"^[ \t]*режим[ \t]*:[ \t]*(.+?)[ \t]*$", re.M)
# Кавычки и апострофы вокруг значения — косметика записи, а не часть номера. Метка
# пишется `printf`-ом без кавычек, но человек правит её руками и кавычки ставит.
TRIM = " \t\"'"


def say(message):
    """Положить строку в контекст сессии и выйти."""
    сказать("SessionStart", "Loreground: " + message)
    sys.exit(0)


def read(path):
    # Только обычные файлы. FIFO и символьное устройство при открытии не ошибаются —
    # они блокируются навсегда, и хук вешает старт сессии вместо того, чтобы упасть.
    if not os.path.isfile(path):
        return None
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except (OSError, UnicodeDecodeError):
        return None


def kit_version(plugin_root):
    """Версия комплекта из его манифеста. None — комплекта на машине нет."""
    if not plugin_root:
        return None
    text = read(os.path.join(plugin_root, ".claude-plugin", "plugin.json"))
    if text is None:
        return None
    try:
        data = json.loads(text)
    except ValueError:
        return None
    # Манифест бывает не объектом (массив, строка) — `.get` на таком падает, а падение
    # хука тихое, то есть неотличимо от «всё в порядке».
    if not isinstance(data, dict):
        return None
    value = data.get("version")
    if not isinstance(value, str):
        return None
    value = value.strip(TRIM)
    return value or None


def main():
    project = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()

    # Ворота. Без метки сборки это чужой проект: сторож молчит и ничего не читает.
    marker_text = read(os.path.join(project, MARKER))
    if marker_text is None:
        return

    kit = kit_version(os.environ.get("CLAUDE_PLUGIN_ROOT"))
    if kit is None:
        # Комплекта рядом нет. Молчание здесь означает не «совпало», а «сравнивать не с
        # чем»: агента увезли на машину, где комплекта нет, — а это законный способ им
        # пользоваться. Говорить об этом каждую сессию значило бы ругать штатное состояние.
        return

    built = BUILT_ON_RE.search(marker_text)
    built_version = built.group(1).strip(TRIM) if built else None
    if not built_version or built_version == UNKNOWN:
        say(
            "в метке " + MARKER + " не записано, на какой версии собран агент "
            "(поле «собран_на_версии»), а комплект на машине — версии " + kit + ". "
            "Расхождение отследить нечем. Скажи об этом человеку: дописать версию "
            "задним числом нельзя, её надо взять из истории сборки или признать "
            "неизвестной осознанно."
        )

    if built_version == kit:
        return  # Совпало — молчим. Каждая строка на старте оплачивается всеми сессиями.

    # Режим БЕРЁТСЯ ИЗ МЕТКИ, а не угадывается по наличию папки. Угадывание давало не
    # молчание, а ЛОЖНЫЙ диагноз: у наполовину переведённого агента (правила зовут
    # комплект, забытая папка standard/ лежит рядом) сторож печатал «само ничего не
    # сменилось», тогда как правила сменились. Ложный красный обесценивает сторожа так
    # же надёжно, как ложный зелёный, — его начинают пролистывать.
    mode = MODE_RE.search(marker_text)
    mode = mode.group(1).strip(TRIM).casefold() if mode else None
    if mode == "копия":
        tail = (
            "Стандарт лежит у самого агента (папка standard/), поэтому база продолжает жить "
            "по правилам версии " + built_version + " — само ничего не сменилось. "
            "Обновление — отдельное осознанное действие."
        )
    elif mode == "указатель":
        tail = (
            "Ядро подключено указателем — значит правила под базой уже сменились "
            "на " + kit + ", хотя база разложена по " + built_version + ". "
            "Это расхождение работает прямо сейчас."
        )
    else:
        # Третий исход, а не выбор одной из двух концовок наугад: не зная режима, сказать
        # «правила сменились» или «ничего не сменилось» одинаково нельзя.
        tail = (
            "Режим подключения ядра в метке не объявлен (поле «режим»), поэтому сказать, "
            "сменились ли правила под базой, нечем: при копии — нет, при указателе — уже да. "
            "Объявить режим строкой в метке."
        )

    say(
        "агент собран на версии " + built_version + ", комплект на машине — "
        + kit + ". " + tail + " Порядок обновления — core.md § 9.3.1 «Обновление ядра "
        "у уже собранного агента»; у агента на прошлой версии этого раздела в своей "
        "копии может не быть — тогда читать в комплекте. Скажи об этом человеку."
    )




if __name__ == "__main__":
    try:
        main()
    except Exception as err:
        сломался("version-drift.py", err, "SessionStart")
    sys.exit(0)
