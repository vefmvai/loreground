r"""Как хук кладёт строку в контекст. Один дом на весь комплект.

Зачем отдельный файл. Печать была скопирована пять раз — четырьмя хуками и
`_broken.py`, — и вместе с ней копировалось решение о кодировке. Решение оказалось
неверным, и чинить пришлось бы пять мест: ровно тот случай, против которого написано
«у факта один дом» (core.md § 6). Теперь дом один, и следующий хук получает верную
печать, ничего о ней не зная.

Почему кодировка называется явно. `json.dump` пишет в `sys.stdout`, а тот по умолчанию
берёт кодировку у системы. На русской Windows это cp1251: байты на выходе — не UTF-8,
хотя читающая сторона ждёт именно его, и кириллица приезжает битой. Кодировка потока —
факт, который обязан задавать комплект, а не локаль машины.

Почему не только escape-последовательности. `ensure_ascii=True` (умолчание `json`)
увёл бы кириллицу в `\uXXXX` и от локали не зависел вовсе — но у вывода два читателя,
а не один. Второй — человек: сообщение о поломке само велит прогнать хук руками и
прочитать причину, а `Не` не читает никто. Поэтому escape здесь запасной
выход, а не основной: он включается ровно тогда, когда кодировку потока назначить не
удалось, и лучше некрасиво, чем битыми байтами.
"""

import json
import sys


def сказать(событие, текст):
    """Отдать хозяину сессии одну строку контекста. Выход из процесса — за вызывающим."""
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        escape = False
    except (AttributeError, ValueError, OSError):
        # Поток подменён и настоящим не является: у него нет `reconfigure` либо он уже
        # закрыт. Назначить кодировку нечему — уводим весь текст в ASCII, он совпадает
        # с UTF-8 побайтово при любой локали. Читаемость теряем, содержание — нет.
        escape = True
    json.dump(
        {"hookSpecificOutput": {"hookEventName": событие, "additionalContext": текст}},
        sys.stdout,
        ensure_ascii=escape,
    )
    sys.stdout.write("\n")
