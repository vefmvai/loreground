"""Общий ответ хука на собственную поломку. Один дом на все четыре.

Зачем отдельный файл, а не копия в каждом хуке: текст сообщения и решение
«говорить, а не молчать» — один факт, и четыре его копии разойдутся при первой
же правке (core.md § 6). Копия оправдана там, где загрузка обязана состояться
без нашего кода, — здесь не тот случай: файл лежит рядом со скриптом.

Прежде каждый хук глушил любую свою ошибку молча. Довод был про шум: хук
отрабатывает при каждом старте, и постоянная поломка дала бы одну и ту же строку
двадцать раз за день. Довод отвергнут: без Python в этом комплекте не работает
вообще ничего, а «сломанный сторож, о котором не сказали» — ложное чувство
защиты. Кому шум не нужен, выключает хук у себя; это его осознанное решение.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _out import сказать  # noqa: E402


def сломался(имя, err, событие):
    """Назвать свою поломку одной строкой и выйти без падения.

    Строка адресована человеку, а не отладчику: тип ошибки, короткое сообщение,
    команда для ручного прогона и способ выключить. Трейсбека нет намеренно.
    """
    # Команда для ручного прогона называется целиком: свой интерпретатор и свой путь.
    # Прежде здесь стояло `python3 <папка плагина>/hooks/<имя>` — человеку приходилось
    # искать папку самому, а `python3` на его машине мог оказаться другим Python, и тогда
    # ручной прогон не воспроизводил поломку вовсе. Оба ответа код знает про себя сам.
    команда = sys.executable + " " + os.path.join(os.path.dirname(os.path.abspath(__file__)), имя)
    текст = (
        "Loreground: хук «" + имя + "» не отработал — " + type(err).__name__ +
        ": " + str(err)[:200] + ".\n"
        "Это НЕ «всё в порядке»: проверка не выполнялась. Прогони его руками, "
        "чтобы увидеть причину целиком:\n"
        "    " + команда + "\n"
        "Не нужен — выключи его в настройках хуков; молча он больше не падает."
    )
    сказать(событие, текст)
