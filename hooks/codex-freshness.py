#!/usr/bin/env python3
"""Сторож свежести кодекса: событие SessionStart.

Кодекс лежит копией в файле правил агента, потому что обязательная загрузка не может
опираться на строку «прочитай там-то» (core.md § 9.3 п. 5). Цена копии — она стареет
молча: обновление комплекта файла правил не касается. Этот сторож делает старение
громким.

Три исхода, и они намеренно различимы:
  • версии совпали              — молчит (ни строки в контекст);
  • версии разошлись/копии нет  — называет расхождение;
  • проверить не удалось        — говорит именно это, а не молчит.

Третий исход отделён от первого по той же причине, по которой у валидатора есть код
выхода 2: «проверил и чисто» и «не смог проверить» — разные факты, и молчание вместо
второго читается как первое.

Честная граница. Сверяются **номер версии и присутствие текста**, а не текст целиком.
Присутствие проверяется пробами: каждая содержательная строка живого источника ищется
в правилах, пробелы при сравнении схлопываются (перенос абзацев — не потеря кодекса).
Поэтому сторож ловит подмену копии ссылкой и обрезанный блок, но **НЕ** заметит правку
внутри уцелевшей строки и не судит о порядке пунктов. Своё и доменное, дописанное
**ниже** блока (§ 9.1 п. 7), он не трогает. Граница названа здесь, потому что молчание
про неё читается как «сверен весь текст».
"""
import json
import os
import re
import sys

MARK_OPEN = "<!-- КОПИРОВАТЬ ОТСЮДА -->"
MARK_CLOSE = "<!-- КОПИРОВАТЬ ДО СЮДА -->"
VERSION_RE = re.compile(r"версия кодекса\s+(\d+)")
# Копию опознаёт строка, которая называет И источник, И версию, — это первая строка
# копируемого блока. Голое «версия кодекса N» копией не считается: та же фраза попадается
# в обычной прозе файла правил, и по ней сторож молчал бы там, где копии нет вовсе.
# Молчание — самый дорогой из трёх исходов: его читают как «всё в порядке».
COPY_RE = re.compile(r"^.*codex\.md.*версия кодекса\s+(\d+).*$", re.M)
# Запасное опознание — по тексту со схлопнутыми пробелами: редактор, переносящий
# абзацы, разрывает строку версии, и построчное правило её теряет. Расстояние
# ограничено намеренно: без предела «codex.md» в начале файла склеился бы с
# «версия кодекса N» где-то далеко ниже, и сторож принял бы за копию чужие строки.
COPY_FLAT_RE = re.compile(r"codex\.md.{0,200}?версия кодекса\s+(\d+)")
RULES_FILES = ("CLAUDE.md", "AGENTS.md", ".cursorrules")
MARKER = ".loreground"


def say(message):
    """Положить строку в контекст сессии и выйти."""
    json.dump(
        {
            "hookSpecificOutput": {
                "hookEventName": "SessionStart",
                "additionalContext": "Loreground: " + message,
            }
        },
        sys.stdout,
        ensure_ascii=False,
    )
    sys.stdout.write("\n")
    sys.exit(0)


def read(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except (OSError, UnicodeDecodeError):
        return None


def copy_block(text):
    """Блок между маркерами. Вне блока версия не ищется: за маркерами живёт шапка."""
    start = text.find(MARK_OPEN)
    end = text.find(MARK_CLOSE)
    if start == -1 or end == -1 or end < start:
        return None
    return text[start + len(MARK_OPEN):end]


def main():
    project = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()

    # Ворота. Без метки сборки это чужой проект: сторож молчит и ничего не читает.
    # Именно `isfile`, а не `exists`: папка с таким именем — не метка. Ворота у ВСЕХ
    # четырёх хуков комплекта объявлены одни (`hooks.json`), значит совпадают и на краях;
    # пока их было два сорта, `mkdir .loreground` глушил ровно двух сторожей, а двое
    # других продолжали говорить — агент выглядел оснащённым при мёртвой слежке.
    if not os.path.isfile(os.path.join(project, MARKER)):
        return

    # Источник: перенесённый стандарт агента («Копия») либо, если своего нет, комплект
    # рядом («Указатель»).
    #
    # Порядок именно такой, и он важнее, чем кажется. Копия кодекса в правилах агента
    # обязана совпадать с ТЕМ стандартом, по которому живёт сам агент, а живёт он по
    # своему. Спроси сначала комплект — и у агента, сознательно стоящего на прошлой
    # версии, сторож объявит устаревшим кодекс, который на самом деле в порядке. Это
    # ложная тревога, а ложная тревога убивает сторожа надёжнее молчания: её начинают
    # пролистывать. Расхождение агента с комплектом — отдельный факт, и у него
    # отдельный сторож (version-drift.py).
    candidates = [os.path.join(project, "standard", "codex.md")]
    plugin_root = os.environ.get("CLAUDE_PLUGIN_ROOT")
    if plugin_root:
        candidates.append(os.path.join(plugin_root, "standard", "codex.md"))

    source_text = source_path = None
    for candidate in candidates:
        text = read(candidate)
        if text is not None:
            source_text, source_path = text, candidate
            break

    if source_text is None:
        say(
            "источник кодекса не найден (искал: "
            + ", ".join(candidates)
            + "). Свежесть копии в правилах агента проверить нечем — это не «всё в порядке»."
        )

    block = copy_block(source_text)
    if block is None:
        say(
            "в источнике " + source_path + " нет пары маркеров КОПИРОВАТЬ — "
            "непонятно, что считать кодексом. Проверка не состоялась."
        )

    source_version = VERSION_RE.search(block)
    if source_version is None:
        say(
            "в источнике " + source_path + " нет строки «версия кодекса N». "
            "Сравнивать не с чем — проверка не состоялась."
        )

    # Берётся первый файл правил, где копия ЕСТЬ, а не первый существующий: рядом с
    # CLAUDE.md часто лежит AGENTS.md, и копия бывает в нём. Судить по первому попавшемуся
    # значило обвинять в пропаже того, что лежит в соседнем файле, — и подталкивать
    # человека завести кодексу второй дом, вопреки центральному правилу стандарта.
    rules_path = rules_text = copy_version = None
    seen = []
    for name in RULES_FILES:
        path = os.path.join(project, name)
        text = read(path)
        if text is None:
            continue
        seen.append(path)
        found = COPY_RE.search(text) or COPY_FLAT_RE.search(" ".join(text.split()))
        if found is not None:
            rules_path, rules_text, copy_version = path, text, found
            break

    if not seen:
        say(
            "файл правил агента не найден (искал "
            + ", ".join(RULES_FILES)
            + "). Куда положена копия кодекса — неизвестно, проверка не состоялась."
        )

    if copy_version is None:
        say(
            "кодекса нет ни в одном файле правил (просмотрены: " + ", ".join(seen)
            + "): строки, которая называет codex.md и «версия кодекса N», в них не найдено. "
            "Кодекс обязан лежать копией в начале правил (core.md § 9.3 п. 5). "
            "Скажи об этом человеку."
        )

    # Версия совпала — но совпала ВЕРСИЯ, а не текст. Строки «Кодекс: см. codex.md,
    # версия кодекса 1» хватало, чтобы сторож замолчал: файл правил без единого пункта
    # кодекса объявлялся здоровым. Это ровно та форма, ради отказа от которой кодекс и
    # кладут копией (§ 9.3 п. 5): ссылка вместо текста.
    #
    # Проверка идёт по ПРОБАМ — по нескольким кускам живого источника сразу, а не по
    # одной «самой длинной строке». Одна строка проваливала всё разом: в блоке без
    # длинных строк проб не находилось и проверка выключалась МОЛЧА, а обрезанную копию
    # она пропускала, если уцелевший верх содержал ту самую строку.
    #
    # Пробелы схлопываются с обеих сторон: перенос абзацев редактором — не потеря
    # кодекса, и ругаться на него значит выдать ложную тревогу, а она убивает сторожа
    # надёжнее молчания.
    def flat(text):
        return " ".join(text.split())

    rules_flat = flat(rules_text)
    probes = [flat(ln)[:60] for ln in block.splitlines()
              if len(flat(ln)) >= 40 and "версия кодекса" not in ln]

    if not probes:
        # Нечего проверять — это ТРЕТИЙ исход, а не первый. Молчание здесь читалось бы
        # как «текст на месте», хотя мы просто не смогли посмотреть.
        say(
            "в источнике " + source_path + " не нашлось ни одного куска текста, по "
            "которому можно узнать копию (нужны строки длиннее 40 знаков). Присутствие "
            "кодекса в правилах проверить нечем — это не «всё в порядке»."
        )

    missing = [pr for pr in probes if pr not in rules_flat]
    if missing:
        say(
            "копия кодекса в " + rules_path + " неполна: из " + str(len(probes))
            + " кусков блока не найдено " + str(len(missing))
            + ". Строка про версию есть, а текста нет — перенеси блок между маркерами "
            "КОПИРОВАТЬ целиком (core.md § 9.3 п. 5). Скажи об этом человеку."
        )

    if copy_version.group(1) == source_version.group(1):
        return  # Совпало — молчим. Каждая строка на старте оплачивается всеми сессиями.

    say(
        "кодекс в правилах агента устарел: копия версии "
        + copy_version.group(1)
        + " в " + rules_path
        + ", источник версии " + source_version.group(1)
        + " в " + source_path
        + ". Скажи об этом человеку и предложи перенести блок между маркерами "
        "КОПИРОВАТЬ заново. Сам файл правил без его согласия не переписывай."
    )




# Ответ на собственную поломку — общий для всех хуков, дом один: _broken.py.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _broken import сломался  # noqa: E402

if __name__ == "__main__":
    try:
        main()
    except Exception as err:
        сломался("codex-freshness.py", err, "SessionStart")
    sys.exit(0)
